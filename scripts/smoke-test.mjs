import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const html=fs.readFileSync(new URL('index.html',root),'utf8');
assert.match(html,/<!doctype html>/i);
assert.match(html,/<canvas[^>]+id="scene"/);
assert.match(html,/id="start"/);
assert.match(html,/name="viewport"/);
assert.match(html,/assets\/nyc-family-sprite\.jpg/);
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
new vm.Script(scripts[0][1],{filename:'merge-game.js'});
for(const f of ['function merge(','function drop(','function physics(','function lose(','function drawTile(','pointerdown','pointerup','localStorage','requestAnimationFrame'])assert.ok(scripts[0][1].includes(f),'Missing '+f);
const photo=fs.readFileSync(new URL('assets/nyc-family-sprite.jpg',root));
assert.ok(photo.length>2000);
assert.equal(photo[0],0xff);assert.equal(photo[1],0xd8);
console.log('NYC Memories: smoke tests passed.');
