import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const html=fs.readFileSync(new URL('index.html',root),'utf8');
assert.match(html,/<canvas[^>]+id="scene"/);
assert.match(html,/NYC Memories/i);
assert.match(html,/assets\/nyc-family-sprite\.jpg/);
assert.ok(!html.includes('game3d.js'),'Removed game must not load');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
new vm.Script(scripts[0][1],{filename:'nyc-merge.js'});
const sprite=fs.readFileSync(new URL('assets/nyc-family-sprite.jpg',root));
assert.ok(sprite.length>2000);
assert.equal(sprite[0],255);
assert.equal(sprite[1],216);
assert.ok(!fs.existsSync(new URL('game3d.js',root)));
assert.ok(!fs.existsSync(new URL('legacy-2d.html',root)));
console.log('PASS: NYC Memories Merge restored; four-level game removed.');
